#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),path=require("node:path"),cp=require("node:child_process");
const ROOT=path.resolve(__dirname,"../.."),DOC=path.join(ROOT,"doc/resource-robust-continuous-local-geometry-representation");
const AUTH=path.join(DOC,"authorizations/STAGE_0_TECHNICAL_AUTHORIZATION.json"),TRIGGER=path.join(DOC,"authorizations/rrclgr-stage0-trigger.txt");
function need(x,m){if(!x)throw new Error(m);}function git(...a){return cp.execFileSync("git",a,{cwd:ROOT,encoding:"utf8"}).trim();}
const auth=JSON.parse(fs.readFileSync(AUTH,"utf8")),token=fs.readFileSync(TRIGGER,"utf8").trim();
need(auth.studyId==="RRCLGR-STUDY1","study mismatch");
need(auth.stageId==="RRCLGR-S0-TECHNICAL-2026-09-03-v1","stage mismatch");
need(auth.authorizationDecision==="STAGE0-TECHNICAL-AUTHORIZED","authorization missing");
need(auth.scientificInferenceAuthorized===false,"scientific inference enabled");
need(auth.stage1ScientificExecutionAuthorized===false&&auth.stage2ScientificExecutionAuthorized===false,"fresh scientific stage enabled");
need(auth.g310ScientificExecutionAuthorized===false,"G3-10 unexpectedly enabled");
need(auth.protectedDepth10AccessAuthorized===false,"protected depth10 enabled");
need(auth.sameVersionAutomaticRerunAuthorized===false,"rerun enabled");
need(auth.executionContract.maxTechnicalExecutions===1,"execution ceiling mismatch");
need(token===auth.executionContract.triggerToken,"trigger token mismatch");
git("merge-base","--is-ancestor",auth.toolingCommit,"HEAD^");
const changed=git("diff","--name-only","HEAD^","HEAD").split("\n").filter(Boolean);
need(changed.length===1&&changed[0]===auth.executionContract.triggerPath,"trigger commit changed unexpected files");
for(const [p,blob] of Object.entries(auth.sourceBindings))need(git("hash-object",p)===blob,`blob mismatch ${p}`);
const study=JSON.parse(fs.readFileSync(path.join(DOC,"prereg/STUDY_1_SPEC.json"),"utf8")),s0=JSON.parse(fs.readFileSync(path.join(DOC,"prereg/STAGE_0_TECHNICAL_SPEC.json"),"utf8")),s1=JSON.parse(fs.readFileSync(path.join(DOC,"prereg/STAGE_1_DEVELOPMENT_SPEC.json"),"utf8")),s2=JSON.parse(fs.readFileSync(path.join(DOC,"prereg/STAGE_2_FORMAL_SPEC.json"),"utf8"));
need(study.reviewedMain==="0bcd1695b6dbd044acf2eed91740d282c63dbb07","review baseline mismatch");
need(study.protectedDepth10==="SEALED / NOT GENERATED / NOT READ / NOT PEEKED","protected boundary mismatch");
need(study.seedNamespaces.stage0Technical.start===32009001&&study.seedNamespaces.stage0Technical.end===32009016,"technical namespace mismatch");
need(s0.stage1SeedAccessAuthorized===false&&s0.stage2SeedAccessAuthorized===false,"Stage 0 fresh access enabled");
need(s1.generationAuthorizedAtFreeze===false&&s2.generationAuthorizedAtFreeze===false,"scientific prereg enabled");
need(s1.seedStart===32010001&&s2.seedStart===32020001,"fresh seed namespace changed");
need(study.g310ScientificExecutionAuthorized===false,"G3-10 protocol guard failed");
console.log("RRCLGR_STAGE0_AUTHORIZATION_VERIFIED");
